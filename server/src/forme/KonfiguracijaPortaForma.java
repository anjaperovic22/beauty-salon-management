    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        int port;
        try{
            port = Integer.parseInt(jTextFieldPort.getText());
            if(validan(port)){
                Konfiguracija.getInstance().setProperty("port", String.valueOf(port));
                Konfiguracija.getInstance().sacuvajIzmene();
                JOptionPane.showMessageDialog(this, "Uspeh prilikom konfiguracije!", "USPEH", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            }
        }catch(NumberFormatException nfe){
            JOptionPane.showMessageDialog(this, "Nije ispravno unesen broj porta!", "GRESKA", JOptionPane.ERROR_MESSAGE);
            return;
        }
       
    }                                        

